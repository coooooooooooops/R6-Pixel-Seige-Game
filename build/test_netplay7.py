# 5C-4c(a,b): host ends match -> guests told; late join mid-match as spectator, seated next round
from playwright.sync_api import sync_playwright
from np_helpers import *
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-fake-ui-for-media-stream'])
    # ---------- A: host ends the match ----------
    H=mk(b,'HOSTY'); G=mk(b,'GUESTY'); host(H); connect(H,G)
    H.click('[data-olm="0"]'); H.wait_for_timeout(300); H.click('#lGo'); H.wait_for_timeout(800)
    G.wait_for_function("document.getElementById('scrOps').style.display!=='none'",timeout=8000)
    G.click('#deploy'); G.wait_for_timeout(500); deploy(H,SIDE)
    G.wait_for_function("typeof G!=='undefined'&&G&&G.guest&&G.ents.length>0",timeout=15000)
    H.evaluate("toMenu()"); H.wait_for_timeout(800)
    ok('guest told the host ended the match',G.evaluate("document.getElementById('over').style.display==='flex'&&document.getElementById('ot').textContent==='HOST ENDED THE MATCH'"),G.evaluate("document.getElementById('ot').textContent"))
    G.click('#ob'); G.wait_for_timeout(400)
    ok('guest returns to menu',G.evaluate("!G&&document.getElementById('menu').style.display!=='none'&&document.getElementById('over').style.display==='none'"))
    ok('host broadcast stopped',H.evaluate("NP.on")==False)
    ok('no JS errors (A)',not H.errs and not G.errs,(H.errs,G.errs))
    H.context.close(); G.context.close()
    # ---------- B: late join ----------
    H=mk(b,'HOSTY'); G=mk(b,'LATEGUY'); host(H)
    H.click('#lInvBtn'); H.click('#lNew'); H.wait_for_selector('#pOffer',timeout=15000); offer=H.input_value('#pOffer')
    G.click('#goJoin'); G.click('#jInv summary'); G.fill('#jOffer',offer); G.click('#jMake'); G.wait_for_selector('#jRep:not([hidden])',timeout=15000); reply=G.input_value('#jReply')
    H.click('#mClose'); H.wait_for_timeout(300)
    H.click('[data-olm="0"]'); H.wait_for_timeout(300); H.click('#lGo'); H.wait_for_timeout(800); deploy(H,SIDE)
    ok('host running a match with nobody connected',H.evaluate("G&&!G.guest&&NP.on&&!!NP.role"))
    H.evaluate("startAct()"); H.wait_for_timeout(300)
    t=H.evaluate("(()=>{for(let y=0;y<H;y++)for(let x=0;x<W;x++)if(map[y][x]===3){setTile(x,y,1);return[x,y]}})()")
    H.evaluate("(r=>{document.getElementById('pReply').value=r;document.getElementById('pAcc').click()})(%s)"%__import__('json').dumps(reply))
    G.wait_for_selector('#olLob:not([hidden])',timeout=25000)
    G.wait_for_function("typeof G!=='undefined'&&G&&G.guest&&G.ents.length>0",timeout=20000)
    ok('late joiner got the running match',True)
    ok('late joiner is a spectator (no seat yet)',G.evaluate("NP.self")==-1)
    ok('spectate bar shown',G.evaluate("document.getElementById('npBar').style.display")=='block')
    G.wait_for_timeout(1500)
    ok('late joiner receives snapshots',G.evaluate("NP.stats.snapIn")>10,G.evaluate("NP.stats.snapIn"))
    ok('wall broken before joining is broken for the late joiner',t and G.evaluate("map[%d][%d]"%(t[1],t[0]))==1,t)
    hm=H.evaluate("map.map(r=>r.join('')).join('|').length"); same=H.evaluate("map.map(r=>r.join('')).join('|')")==G.evaluate("map.map(r=>r.join('')).join('|')")
    ok('whole map identical to host',same)
    chk="(()=>{let s=0;for(let y=0;y<H;y++)for(let x=0;x<W;x++)s=(s*31+map[y][x]*7+fk[y*W+x]*13+fc[y*W+x]*3+winF[y*W+x])>>>0;return [s,JSON.stringify([SITES,HOST])]})()"
    ok('map + furniture + windows + sites/hostage identical to host',H.evaluate(chk)==G.evaluate(chk),(H.evaluate(chk),G.evaluate(chk)))
    ok('phase matches host',G.evaluate("G.phase")==H.evaluate("G.phase"))
    # next round: late joiner gets a seat
    H.evaluate("endRound('A','TEST')"); H.wait_for_function("document.getElementById('over').style.display==='flex'",timeout=10000)
    G.wait_for_function("document.getElementById('over').style.display==='flex'",timeout=10000)
    H.click('#ob'); G.click('#ob'); G.wait_for_timeout(500); G.click('#deploy'); G.wait_for_timeout(500)
    H.evaluate("document.getElementById('deploy').click()")
    G.wait_for_function("typeof G!=='undefined'&&G&&G.guest&&G.ents.length>0&&NP.self>=0",timeout=20000)
    ok('late joiner has a seat next round',G.evaluate("NP.self")>=0 and H.evaluate("G.ents.filter(e=>e.rp).length")==1)
    ok('host no remote error',H.evaluate("!NP.err"),H.evaluate("NP.err"))
    print('errs',H.errs,G.errs); ok('no JS errors (B)',not H.errs and not G.errs)
