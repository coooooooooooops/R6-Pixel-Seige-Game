# 5C-11: guests are paid at match end like single player (own kills, win/loss), host's own row stays the host's; effects fade at normal speed
from playwright.sync_api import sync_playwright
from np_helpers import *
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-fake-ui-for-media-stream'])
    H=mk(b,'HOSTY'); G=mk(b,'GUESTY'); host(H); connect(H,G)
    H.click('[data-olm="0"]'); H.wait_for_timeout(300); H.click('#lGo'); H.wait_for_timeout(800)
    G.click('#deploy'); G.wait_for_timeout(500); deploy(H,SIDE)
    G.wait_for_function("typeof G!=='undefined'&&G&&G.guest&&G.ents.length>0&&NP.self>=0",timeout=15000)
    H.evaluate("startAct()"); H.wait_for_timeout(500)
    ok('ECO present on both',H.evaluate("!!window.ECO")and G.evaluate("!!window.ECO"))
    # tracers fade at the normal rate (not twice as fast)
    G.evaluate("G.tr.push({x1:0,y1:0,x2:5,y2:5,t:30,pl:false});window.__f0=G.tr.length")
    G.wait_for_timeout(250); n=G.evaluate("G.tr.filter(t=>t.x2===5&&t.t>0).length")
    ok('tracer with 30 ticks left still alive after ~250 ms (15 ticks)',n==1,n)
    hk=H.evaluate("(G.me.kl=3,G.me.kl)"); gk=H.evaluate("(()=>{const e=G.ents.find(x=>x.rp);e.kl=5;return e.kl})()")
    H.evaluate("score[0]=2;score[1]=0;endRound('A','TEST MATCH')")
    H.wait_for_function("document.getElementById('over').style.display==='flex'",timeout=10000)
    G.wait_for_function("document.getElementById('over').style.display==='flex'&&NP.paid===1",timeout=10000)
    gside=G.evaluate("G.me.side"); won=(gside=='A')
    ok('host sent the stats table',H.evaluate("NP.stats.mstatsOut")==1)
    ok('guest was paid (ECO.matchEnd ran)',G.evaluate("!!ECO.lastMatch&&ECO.lastMatch.credits>0"),G.evaluate("ECO.lastMatch&&ECO.lastMatch.credits"))
    lines=G.evaluate("ECO.lastMatch.lines.map(l=>l[0]+':'+l[1])"); print('guest lines',lines)
    ok('guest kills line is the guest own kills (5)',any(l=='KILLS:5' for l in lines),lines)
    ok('guest win/loss line matches its side',('MATCH WIN:1' in lines)==won and ('PARTICIPATION:1' in lines)==(not won),lines)
    hl=H.evaluate("ECO.lastMatch.lines.map(l=>l[0]+':'+l[1])"); print('host lines',hl)
    ok('host kills line is the host own kills (3), not the guest ones',any(l=='KILLS:3' for l in hl),hl)
    ok('paid only once',G.evaluate("NP.paid")==1)
    G.click('#ob'); G.wait_for_timeout(400)
    ok('guest back at menu and flags reset',G.evaluate("!G&&NP.paid===false&&NP.mstats===null"))
    ok('no JS errors',not H.errs and not G.errs and H.evaluate("!NP.err"),(H.errs,G.errs))
